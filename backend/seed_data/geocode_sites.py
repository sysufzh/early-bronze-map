# Region centroids for fallback
REGION_CENTROIDS = {
    '河西走廊': (98.0, 39.5),
    '河湟地区': (101.5, 36.3),
    '哈密盆地': (93.5, 42.8),
    '黄河中下游地区': (113.5, 35.5),
    '燕山地区': (117.5, 40.5),
    '河套地区': (109.0, 40.5),
    '长江流域': (114.0, 30.5),
    '新疆中西部': (83.0, 41.0),
}


def main():
    db = SessionLocal()
    try:
        # Get all unique site names without coordinates
        results = db.execute(
            select(Artifact.site_name, Artifact.region, func.count(Artifact.id))
            .where(Artifact.geom.is_(None), Artifact.site_name.isnot(None))
            .group_by(Artifact.site_name, Artifact.region)
            .order_by(func.count(Artifact.id).desc())
        ).all()

        total_updated = 0
        not_found = []

        for site_name, region, count in results:
            lon, lat = None, None

            # Try exact match first
            if site_name in SITE_COORDS:
                lon, lat = SITE_COORDS[site_name]
                source = 'known'
            else:
                # Try partial match (site name might be a substring of a known site or vice versa)
                for known_site, coords in SITE_COORDS.items():
                    if site_name in known_site or known_site in site_name:
                        lon, lat = coords
                        source = 'partial'
                        break

            # Fallback to region centroid
            if lon is None and region and region in REGION_CENTROIDS:
                lon, lat = REGION_CENTROIDS[region]
                source = 'region'
                not_found.append((site_name, region, count))

            if lon is not None:
                # Update all artifacts at this site
                db.execute(
                    update(Artifact)
                    .where(
                        Artifact.site_name == site_name,
                        Artifact.geom.is_(None),
                    )
                    .values(geom=func.ST_SetSRID(func.ST_MakePoint(lon, lat), 4326))
                )
                total_updated += count
                print(f"  [{source:7s}] {site_name:20s} ({region or '':10s}) -> {lon:.4f}, {lat:.4f}  ({count} records)")

        db.commit()

        print(f"\nTotal updated: {total_updated} records across {len(results)} sites")
        if not_found:
            print(f"\nSites using region centroid fallback ({len(not_found)}):")
            for site, region, count in not_found:
                print(f"  {site} ({region}) - {count} records")

    finally:
        db.close()


if __name__ == '__main__':
    main()
